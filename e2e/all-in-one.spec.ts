import { test, expect, installE2EPageGuards } from "./support/test";
import { createAdminManagedUser, createProductSubscriptionSeed, productApiFetch } from "./support/product-api";
import { loginThroughProductUI } from "./support/auth";
import { adminUserResponseSchema } from "@renewlet/shared/schemas/admin";
import { financePlansResponseSchema, financeSummaryResponseSchema, financeTransactionsResponseSchema } from "@renewlet/shared/schemas/finance";

test("unified subscription and rent payments, CNY reporting and embedded service views", async ({ page: adminPage, browser, baseURL }, testInfo) => {
  await adminPage.goto("/");
  const email = `unified-${testInfo.project.name}-${Date.now()}@example.com`;
  const password = "unified-test-password";
  const result = adminUserResponseSchema.parse(await createAdminManagedUser(adminPage, { name: "Unified tester", email, password }));
  const context = await browser.newContext({ ...testInfo.project.use, baseURL });
  let guards: Awaited<ReturnType<typeof installE2EPageGuards>> | undefined;
  try {
    await context.clearCookies();
    const page = await context.newPage();
    await loginThroughProductUI(page, email, password);
    guards = await installE2EPageGuards(page);
    const first = financePlansResponseSchema.parse((await productApiFetch(page, "/api/app/finance/plans")).json).data;
    const today = first.today;
    const yesterday = new Date(new Date(today + "T00:00:00Z").getTime() - 86400000).toISOString().slice(0, 10);
    await createProductSubscriptionSeed(page, { name: "Design tool", price: "20", currency: "USD", billingCycle: "monthly", category: "design", startDate: yesterday, nextBillingDate: yesterday, autoRenew: true });
    await page.goto("/subscriptions");
    await expect(page.getByRole("heading", { name: "订阅", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "续费日历", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: "订阅分析", exact: true })).toBeVisible();
    await expect(page.getByTestId("subscription-card").filter({ hasText: "Design tool" }).getByText("待确认", { exact: true }).first()).toBeVisible();
    await page.getByRole("region", { name: "订阅概览", exact: true }).getByRole("button", { name: "确认付款", exact: true }).first().click();
    let dialog = page.getByRole("dialog");
    await expect(dialog.getByRole("heading", { name: "确认付款", exact: true })).toBeVisible();
    await expect(dialog.getByText("订阅-设计创意", { exact: true }).first()).toBeVisible();
    await dialog.getByLabel("实际人民币金额", { exact: true }).fill("146.8");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    let summary = financeSummaryResponseSchema.parse((await productApiFetch(page, "/api/app/finance/reports/summary")).json).data;
    expect(summary.cnyTotals?.grossExpense).toBe("146.8");
    expect(summary.cnyTotals?.recurringExpense).toBe("146.8");
    const records = financeTransactionsResponseSchema.parse((await productApiFetch(page, "/api/app/finance/transactions")).json).data.items;
    expect(records[0]?.currency).toBe("USD"); expect(records[0]?.amount).toBe("20"); expect(records[0]?.cnyAmount).toBe("146.8");
    expect(records[0]?.category).toBe("subscription:design");
    await page.getByRole("button", { name: "续费日历", exact: true }).click();
    await expect(page.getByRole("heading", { name: "续费/到期日历", exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("subscription-calendar.png"), fullPage: true });
    await page.getByRole("button", { name: "订阅分析", exact: true }).click();
    await expect(page.getByRole("heading", { name: "统计分析", exact: true })).toBeVisible();
    await expect(page.getByText("月均支出 (CNY)", { exact: true })).toBeVisible();
    await expect(page.getByTestId("app-header")).toHaveCount(1);
    await page.screenshot({ path: testInfo.outputPath("subscription-analysis.png"), fullPage: true });
    await page.getByRole("button", { name: "付款历史", exact: true }).click();
    await page.getByRole("article").filter({ hasText: "Design tool" }).getByRole("button", { name: "编辑", exact: true }).click();
    dialog = page.getByRole("dialog");
    await expect(dialog.getByText("已付款", { exact: false })).toBeVisible();
    await expect(dialog.getByText(/分类 · 订阅-设计创意/)).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("subscription-payments.png"), fullPage: true });
    await dialog.getByRole("button", { name: "取消", exact: true }).first().click();
    await page.goto("/transactions?view=plans");
    await page.getByRole("button", { name: "添加周期计划", exact: true }).click();
    dialog = page.getByRole("dialog");
    await dialog.getByLabel("计划名称", { exact: true }).fill("Apartment rent");
    await dialog.getByLabel("金额", { exact: true }).fill("1800");
    await dialog.getByLabel("下次付款日期", { exact: true }).fill(today);
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await page.getByRole("article").filter({ hasText: "Apartment rent" }).getByRole("button", { name: "确认付款", exact: true }).click();
    dialog = page.getByRole("dialog");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    summary = financeSummaryResponseSchema.parse((await productApiFetch(page, "/api/app/finance/reports/summary")).json).data;
    expect(summary.cnyTotals?.grossExpense).toBe("1946.8");
    await page.goto("/");
    await expect(page.getByTestId("consumption-overview").getByText("1,946.80 CNY", { exact: true }).first()).toBeVisible();
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("unified-overview-dark.png"), fullPage: true });
    await page.getByRole("button", { name: "切换主题", exact: true }).click();
    await page.screenshot({ path: testInfo.outputPath("unified-overview-light.png"), fullPage: true });
    await page.goto("/statistics");
    await expect(page.getByRole("heading", { name: "分析", exact: true })).toBeVisible();
    await expect(page.getByRole("heading", { name: "商家支出", exact: true })).toBeVisible();
    await page.getByText("查看订阅分类", { exact: true }).click();
    const subscriptionCategoryLink = page.getByRole("link", { name: /订阅-设计创意/ });
    await expect(subscriptionCategoryLink).toBeVisible();
    await subscriptionCategoryLink.click();
    await expect(page.getByLabel("分类", { exact: true })).toHaveValue("subscription:design");
    await expect(page.getByRole("article")).toHaveCount(1);
    await expect(page.getByRole("article").getByText(/订阅-设计创意/)).toBeVisible();
    await page.getByLabel("分类", { exact: true }).selectOption("subscription:");
    await expect(page.getByRole("article")).toHaveCount(1);
    await page.goto("/statistics");
    await page.screenshot({ path: testInfo.outputPath("unified-analysis.png"), fullPage: true });
    await page.getByRole("button", { name: "记一笔", exact: true }).first().click();
    await expect(page.getByRole("dialog").getByRole("heading", { name: "记一笔", exact: true })).toBeVisible();
    dialog = page.getByRole("dialog");
    await dialog.getByLabel("金额", { exact: true }).fill("180");
    await dialog.locator("summary").filter({ hasText: "更多信息" }).click();
    await dialog.getByLabel("商家", { exact: true }).fill("Electricity");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    const created = await productApiFetch(page, "/api/app/finance/plans", { method: "POST", body: { name: "Electricity", type: "bill", amount: "0", currency: "CNY", category: "builtin:utilities", unit: "month", interval: 1, nextDue: today, endDate: "", status: "active", version: 0 } });
    expect(created.ok, created.body).toBe(true);
    await page.goto("/transactions?view=plans");
    await page.getByRole("article").filter({ hasText: "Electricity" }).getByRole("button", { name: "确认付款", exact: true }).click();
    dialog = page.getByRole("dialog");
    await dialog.getByRole("button", { name: "关联已有账单", exact: true }).click();
    const option = dialog.locator("option").filter({ hasText: "Electricity" });
    await expect(option).toHaveCount(1);
    await dialog.getByLabel("流水", { exact: true }).selectOption(await option.getAttribute("value") ?? "");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    const linkedRecords = financeTransactionsResponseSchema.parse((await productApiFetch(page, "/api/app/finance/transactions")).json).data.items;
    expect(linkedRecords).toHaveLength(3);
    expect(linkedRecords.find((record) => record.merchant === "Electricity")?.planId).not.toBe("");
    await page.getByRole("article").filter({ hasText: "Electricity" }).getByRole("button", { name: "确认付款", exact: true }).click();
    dialog = page.getByRole("dialog");
    await dialog.getByRole("button", { name: "跳过本期", exact: true }).click();
    await dialog.getByLabel("跳过原因", { exact: true }).fill("本期无需付款");
    await dialog.getByRole("button", { name: "保存", exact: true }).click();
    await expect(dialog).not.toBeVisible();
    const afterSkip = financePlansResponseSchema.parse((await productApiFetch(page, "/api/app/finance/plans")).json).data;
    expect(afterSkip.payments.some((payment) => payment.status === "skipped" && payment.reason === "本期无需付款")).toBe(true);
  } finally {
    await guards?.close();
    await context.close();
    const removed = await productApiFetch(adminPage, `/api/app/admin/users/${result.data.user.id}`, { method: "DELETE" });
    expect(removed.ok, removed.body).toBe(true);
  }
});
